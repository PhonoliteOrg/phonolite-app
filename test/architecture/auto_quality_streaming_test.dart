class _DecodedOutput extends MemoryPcmOutput {
  final samples = <int>[];

  @override
  Future<void> writePcm32(Int32List samples) async {
    this.samples.addAll(samples.map((value) => value >> 16));
    await super.writePcm32(samples);
  }

  @override
  Future<void> write(Int16List samples) async {
    this.samples.addAll(samples);
    await super.write(samples);
  }
}

class _ProgressOutput extends _DecodedOutput {
  int _played = 0;
  int _pendingDone = 0;

  void advanceTo(int samples) {
    _pendingDone += samples - _played;
    _played = samples;
  }

  @override
  Future<int> collectDoneSamples() async {
    final done = _pendingDone;
    _pendingDone = 0;

    return done;
  }

  @override
  Future<bool> isIdle() async => samples.isNotEmpty && _played >= samples.length;
}

void main() {
  final nativeLibrary = Platform.environment['PHONOLITE_OPUS_LIBRARY'];
  final enabled = nativeLibrary != null && File(nativeLibrary).existsSync();
  if (enabled) {
    ffi.DynamicLibrary.open(File(nativeLibrary).absolute.path);
  }

  test('quality telemetry follows playback through prefetched real renditions', () async {
    final fixture = jsonDecode(File('test/fixtures/audio/auto_quality_ranges.json').readAsStringSync()) as Map;
    final output = _ProgressOutput();
    final harness = AudioPlaybackHarness(
      transport: _transportFor(fixture),
      settings: const StreamSettings(mode: 'auto', quality: 'high'),
      decoderFactory: (rate, channels) => OpusDecoder(sampleRate: rate, channels: channels),
      outputFactory: (_, __, ___) => output,
    );
    addTearDown(harness.close);
    harness.start();
    final rate = fixture['sample_rate'] as int;
    await waitUntil(() => output.samples.length == (fixture['duration_ms'] as int) * rate ~/ 1000);

    for (final (positionMs, quality) in [
      (0, 'medium'),
      (239, 'medium'),
      (240, 'low'),
      (479, 'low'),
      (480, 'medium'),
      (719, 'medium'),
      (720, 'high'),
      (959, 'high'),
      (960, 'low'),
    ]) {
      output.advanceTo(positionMs * rate ~/ 1000);
      await harness.collectStats();
      await waitUntil(
        () => harness.messages.lastWhere((message) => message['type'] == 'stats')['position_ms'] == positionMs,
      );
      final stats = harness.messages.lastWhere((message) => message['type'] == 'stats');
      expect(
        stats['stream_quality'],
        quality,
        reason: 'Audible quality at $positionMs ms after all ranges are decoded.',
      );
    }
    await harness.pause();
    await harness.collectStats();
    expect(harness.messages.lastWhere((message) => message['type'] == 'stats')['stream_quality'], 'low');
  }, skip: enabled ? false : 'Set PHONOLITE_OPUS_LIBRARY to the compiled native Opus library.');

  test('real fixed-quality switches retain one output and continuous presentation', () async {
    // Generated by the server's mixed-rendition test from one deterministic WAV.
    final fixture = jsonDecode(File('test/fixtures/audio/auto_quality_ranges.json').readAsStringSync()) as Map;
    final ranges = (fixture['ranges'] as List).cast<Map>();
    final transport = _transportFor(fixture);
    final output = _DecodedOutput();
    var outputs = 0;
    final harness = AudioPlaybackHarness(
      transport: transport,
      settings: const StreamSettings(mode: 'auto', quality: 'high'),
      decoderFactory: (rate, channels) => OpusDecoder(sampleRate: rate, channels: channels),
      outputFactory: (_, __, ___) {
        outputs++;

        return output;
      },
    );
    addTearDown(harness.close);
    harness.start();
    await waitUntil(() => harness.messages.any((message) => message['type'] == 'complete'));

    final rate = fixture['sample_rate'] as int;
    expect(output.samples, hasLength((fixture['duration_ms'] as int) * rate ~/ 1000));
    expect(transport.requestedPositions, ranges.map((range) => range['start_ms']).toList());
    expect(outputs, 1);
    expect(output.flushes, 0);
    expect(harness.messages.where((message) => message['type'] == 'started'), hasLength(1));
    expect(harness.messages.where((message) => message['type'] == 'complete'), hasLength(1));
    expect(
      harness.messages.where((message) => message['text']?.toString().startsWith('Auto audio rendition:') == true),
      hasLength(ranges.length - 1),
    );

    for (final range in ranges.skip(1)) {
      final center = (range['start_ms'] as int) * rate ~/ 1000;
      var error = 0.0;
      var energy = 0.0;
      for (var index = center - 240; index < center + 240; index++) {
        final expected = math.sin(index * (fixture['angular_frequency'] as num)) * (fixture['amplitude'] as num);
        error += math.pow(output.samples[index] - expected, 2);
        energy += expected * expected;
      }
      // Frame shifts, repeated samples, silence and large boundary transients
      // fail this signal check even when the total frame count happens to match.
      expect(error / energy, lessThan(0.05), reason: 'Continuity at ${range['start_ms']} ms');
    }
  }, skip: enabled ? false : 'Set PHONOLITE_OPUS_LIBRARY to the compiled native Opus library.');
}

MemoryQuic _transportFor(Map fixture) {
  final ranges = (fixture['ranges'] as List).cast<Map>();
  final transport = MemoryQuic();
  transport.onRequest = (position, seekId) {
    final range = ranges.singleWhere((range) => range['start_ms'] == position);
    transport.events.add({
      'type': 'stream',
      'request_id': transport.requestId,
      'position_ms': position,
      'range_end_ms': range['end_ms'],
      'end_of_track': range['end_ms'] == fixture['duration_ms'],
      'source_version': 'one-fixed-source',
      'adaptive_ranges': true,
    });
    if (seekId != null) {
      final marker = Uint8List(6)..setAll(0, [255, 255]);
      ByteData.sublistView(marker).setUint32(2, seekId, Endian.little);
      transport.chunks.add(marker);
    }
    final payload = Uint8List.fromList((range['payload'] as List).cast<int>());
    // Split headers and packets across reads, as a real QUIC delivery can.
    for (var offset = 0; offset < payload.length; offset += 137) {
      transport.chunks.add(Uint8List.sublistView(payload, offset, math.min(offset + 137, payload.length)));
    }
  };
  return transport;
}
