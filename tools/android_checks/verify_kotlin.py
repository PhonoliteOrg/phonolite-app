"""Compile handwritten Android Kotlin and run JVM contracts without Gradle or Android runtime.

Uses the project's cached Kotlin compiler, Android SDK, Flutter embedding and AndroidX
artifacts. Resource IDs are generated by aapt2 from the real app resources. This does
not build/package the complete Flutter app, rebuild native packages or launch a device.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import xml.etree.ElementTree as ET
import zipfile


APP_ROOT = Path(__file__).resolve().parents[2]
SOURCE_ROOT = APP_ROOT / "android/app/src"
TEST_MAINS = (
    "com.example.phonolite_app.infrastructure.audio.AudioPlaybackProgressTest",
    "com.example.phonolite_app.application.controllers.media.NativeMediaControllerTest",
    "com.example.phonolite_app.application.controllers.vehicle.VehicleBrowseControllerTest",
    "com.example.phonolite_app.infrastructure.flutter.NativeChannelContractTest",
    "com.example.phonolite_app.infrastructure.media.MediaServiceConnectionTest",
)


def run(arguments: list[str | Path]) -> None:
    completed = subprocess.run([str(argument) for argument in arguments], cwd=APP_ROOT)
    if completed.returncode:
        raise SystemExit(completed.returncode)


def version_key(path: Path) -> tuple[int, ...]:
    return tuple(int(part) for part in re.findall(r"\d+", path.name))


def fresh_output_directory(output: Path, name: str) -> Path:
    destination = output / name
    if destination.exists():
        if destination.resolve().parent != output.resolve() or name not in {"classes", "generated", "resource_classes"}:
            raise ValueError(f"Refusing to clear output outside the selected build directory: {destination}")
        shutil.rmtree(destination)
    destination.mkdir(parents=True, exist_ok=True)

    return destination


def local_properties() -> dict[str, str]:
    path = APP_ROOT / "android/local.properties"
    if not path.exists():
        return {}

    return {
        key.strip(): value.strip().replace("\\\\", "\\").replace("\\:", ":")
        for line in path.read_text(encoding="utf-8").splitlines()
        if "=" in line and not line.lstrip().startswith("#")
        for key, value in [line.split("=", 1)]
    }


def cached_jar(cache: Path, group: str, artifact: str, version: str | None = None) -> Path:
    artifact_root = cache / group / artifact
    versions = [artifact_root / version] if version else sorted(artifact_root.iterdir(), key=version_key, reverse=True)
    for candidate in versions:
        jars = [path for path in candidate.rglob("*.jar") if not path.stem.endswith(("-sources", "-javadoc"))]
        if jars:
            return jars[0]

    raise FileNotFoundError(f"Missing cached {group}:{artifact}:{version or 'any version'}")


def androidx_classpath(cache: Path, output: Path) -> list[Path]:
    libraries = output / "androidx"
    libraries.mkdir(parents=True, exist_ok=True)
    classpath: list[Path] = []
    for group in sorted(cache.glob("androidx.*")):
        for artifact in sorted(group.iterdir()):
            versions = sorted((path for path in artifact.iterdir() if path.is_dir()), key=version_key, reverse=True)
            for version in versions:
                archives = list(version.rglob("*.aar"))
                jars = [path for path in version.rglob("*.jar") if not path.stem.endswith(("-sources", "-javadoc"))]
                if not archives and not jars:
                    continue

                classpath.extend(jars)
                for archive in archives:
                    destination = libraries / f"{group.name}-{artifact.name}-{version.name}.jar"
                    with zipfile.ZipFile(archive) as packaged:
                        if "classes.jar" in packaged.namelist():
                            destination.write_bytes(packaged.read("classes.jar"))
                            classpath.append(destination)
                break

    return classpath


def generate_resource_classes(sdk: Path, android_jar: Path, java: Path, output: Path) -> Path:
    tools = sorted((sdk / "build-tools").iterdir(), key=version_key, reverse=True)[0]
    aapt = tools / ("aapt2.exe" if os.name == "nt" else "aapt2")
    generated = fresh_output_directory(output, "generated")
    resource_classes = fresh_output_directory(output, "resource_classes")

    manifest = ET.parse(SOURCE_ROOT / "main/AndroidManifest.xml")
    manifest.getroot().set("package", "com.example.phonolite_app")
    ET.register_namespace("android", "http://schemas.android.com/apk/res/android")
    manifest_path = output / "AndroidManifest.xml"
    manifest.write(manifest_path, encoding="utf-8", xml_declaration=True)

    run([aapt, "compile", "--dir", SOURCE_ROOT / "main/res", "-o", output / "resources.zip"])
    run([
        aapt, "link", "--manifest", manifest_path, "-I", android_jar,
        "--java", generated, "-o", output / "resources.apk", output / "resources.zip",
    ])
    javac = java.with_name("javac.exe" if os.name == "nt" else "javac")
    run([javac, "--release", "11", "-d", resource_classes, *generated.rglob("*.java")])

    return resource_classes


def main() -> None:
    properties = local_properties()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--android-sdk", type=Path, default=properties.get("sdk.dir", os.getenv("ANDROID_HOME")))
    parser.add_argument("--flutter-sdk", type=Path, default=properties.get("flutter.sdk", os.getenv("FLUTTER_ROOT")))
    parser.add_argument("--gradle-user-home", type=Path, default=Path(os.getenv("GRADLE_USER_HOME", Path.home() / ".gradle")))
    parser.add_argument("--java", type=Path, default=shutil.which("java"))
    parser.add_argument("--compile-sdk", type=int)
    parser.add_argument("--output", type=Path, default=APP_ROOT / ".dart_tool/android_architecture_refactor/checks")
    args = parser.parse_args()

    if not args.android_sdk or not args.flutter_sdk or not args.java:
        parser.error("Android SDK, Flutter SDK and Java are required; pass their paths or configure local.properties/PATH")

    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    cache = args.gradle_user_home / "caches/modules-2/files-2.1"
    settings = (APP_ROOT / "android/settings.gradle.kts").read_text(encoding="utf-8")
    kotlin_version = re.search(r'id\("org.jetbrains.kotlin.android"\) version "([^"]+)"', settings)[1]
    flutter_extension = args.flutter_sdk / "packages/flutter_tools/gradle/src/main/kotlin/FlutterExtension.kt"
    compile_sdk = args.compile_sdk or int(re.search(r"compileSdkVersion: Int = (\d+)", flutter_extension.read_text())[1])
    android_jar = args.android_sdk / f"platforms/android-{compile_sdk}/android.jar"
    engine_root = args.flutter_sdk / "bin/cache/artifacts/engine"
    flutter_jar = next(engine_root.glob("android-*/flutter.jar"))

    compiler = [cached_jar(cache, "org.jetbrains.kotlin", artifact, kotlin_version) for artifact in (
        "kotlin-compiler-embeddable", "kotlin-stdlib", "kotlin-script-runtime", "kotlin-reflect", "kotlin-daemon-embeddable",
    )]
    compiler.extend([
        cached_jar(cache, "org.jetbrains.intellij.deps", "trove4j"),
        cached_jar(cache, "org.jetbrains.kotlinx", "kotlinx-coroutines-core-jvm"),
        cached_jar(cache, "org.jetbrains", "annotations"),
    ])
    resources = generate_resource_classes(args.android_sdk, android_jar, args.java, output)
    classpath = [android_jar, flutter_jar, resources, compiler[1], compiler[-1], *androidx_classpath(cache, output)]
    sources = sorted((SOURCE_ROOT / "main/kotlin").rglob("*.kt"))
    tests = sorted((SOURCE_ROOT / "test/kotlin").rglob("*.kt"))
    classes = fresh_output_directory(output, "classes")

    run([
        args.java, "-Xmx1536m", "-cp", os.pathsep.join(map(str, compiler)),
        "org.jetbrains.kotlin.cli.jvm.K2JVMCompiler", "-no-stdlib", "-no-reflect", "-jvm-target", "11",
        "-classpath", os.pathsep.join(map(str, classpath)), "-d", classes, *sources, *tests,
    ])

    for test in TEST_MAINS:
        run([args.java, "-cp", os.pathsep.join(map(str, [classes, *classpath])), test])

    verification = {
        "kotlin_version": kotlin_version,
        "compile_sdk": compile_sdk,
        "production_kotlin_files": len(sources),
        "test_kotlin_files": len(tests),
        "headless_test_mains": TEST_MAINS,
        "resources_compiled_and_linked": True,
        "scope": "Real SDK Kotlin/resource compilation and headless JVM contracts; no complete APK or native package rebuild",
    }
    (output / "verification.json").write_text(json.dumps(verification, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(verification, indent=2))


if __name__ == "__main__":
    main()
